def load_frame_ids():
    p = os.path.join(os.path.dirname(C.DATA), 'lumpi_starting_kit',
                     'detection_test_frame_ids.json')
    ids = json.load(open(p))
    if isinstance(ids, dict):
        ids = ids.get('detection_test_frame_ids', ids)
    return [str(i) for i in ids]


def read_bin(path):
    a = np.fromfile(path, dtype=np.float32)
    if a.size % 4 == 0 and a.size % 3 != 0:
        a = a.reshape(-1, 4)[:, :3]
    else:
        a = a.reshape(-1, 3)
    return a


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--ckpt', required=True)
    ap.add_argument('--out', default=os.path.join(C.OUT_DIR, 'submission.zip'))
    ap.add_argument('--score-thr', type=float, default=0.10)
    ap.add_argument('--iou-thr', type=float, default=0.25)
    ap.add_argument('--topk', type=int, default=600,
                    help='每类保留的候选 anchor 数（per_class 模式）')
    ap.add_argument('--synth-dir', default=os.path.join(C.DATA, 'synthetic'))
    ap.add_argument('--no-zip', action='store_true')
    ap.add_argument('--flip', type=int, default=0,
                    help='1 = 镜像 y 轴 TTA（两份预测按类 NMS 合并）')
    ap.add_argument('--moto-from-bike', type=float, default=0.0,
                    help='把每个 Bicycle 预测复制成 Motorcycle，分数乘以此系数（0=关闭）')
    a = ap.parse_args()

    dev = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    model = M.PointPillars().to(dev)
    st = torch.load(a.ckpt, map_location=dev, weights_only=False)
    model.load_state_dict(st['model'])
    model.eval()
    print(f'载入 {a.ckpt}（epoch {st.get("epoch")}, val mAP {st.get("best", -1):.4f}）')

    ids = load_frame_ids()
    preds = {}
    nbox = 0
    for i, fid in enumerate(ids):
        pts = read_bin(os.path.join(C.TEST_FRAMES_DIR, f'{fid}.bin'))
        if a.flip:
            b, s, c = M.detect_tta(model, pts, dev, a.score_thr, a.iou_thr,
                                   topk=a.topk, flips=(1,))
        else:
            b, s, c = M.detect(model, pts, dev, a.score_thr, a.iou_thr,
                               topk=a.topk, moto_from_bike=a.moto_from_bike)
        preds[fid] = [{'box': [round(float(v), 4) for v in bb],
                       'score': round(float(ss), 6),
                       'class': C.CLASS_NAMES[int(cc)]}
                      for bb, ss, cc in zip(b, s, c)]
        nbox += len(b)
        if (i + 1) % 10 == 0:
            print(f'  {i+1}/{len(ids)}  平均 {nbox/(i+1):.0f} 框/帧', flush=True)

    print(f'预测完成：{len(ids)} 帧，{nbox} 个框，平均 {nbox/len(ids):.0f} 框/帧')
    os.makedirs(os.path.dirname(a.out) or '.', exist_ok=True)
    if a.no_zip:
        with open(a.out.replace('.zip', '.json'), 'w') as f:
            json.dump(preds, f)
        print(f'-> {a.out.replace(".zip", ".json")}')
        return

    # 提交包里的 50 帧合成点云：文件名必须是 0001..0050
    src = sorted(f for f in os.listdir(a.synth_dir) if f.endswith('.bin'))
    if len(src) < 50:
        raise SystemExit(f'{a.synth_dir} 只有 {len(src)} 帧合成点云，需要 50 帧')
    with zipfile.ZipFile(a.out, 'w', zipfile.ZIP_DEFLATED) as zf:
        for k in range(50):
            p = os.path.join(a.synth_dir, src[k])
            zf.write(p, f'synthetic/{k+1:04d}.bin')
        zf.writestr('predictions.json', json.dumps(preds))
        zf.writestr('declaration.txt', DECL)
    print(f'打包 {a.out}  ({os.path.getsize(a.out)/1024/1024:.1f} MB)')


if __name__ == '__main__':
    main()
