#!/usr/bin/env python3
"""把提交包里的 declaration.txt 换成更新版（日期、标签、真实数据使用说明）。

保持官方要求的逐字句原样不动，只改事实描述部分。
"""
import json
import os
import shutil
import zipfile

import sys
SRC = 'data/out/_test_final.zip'
DST = sys.argv[1] if len(sys.argv) > 1 else 'data/out/submission_v11.zip'

DECL = """I confirm that I did not train on any frame listed in forbidden_frames.txt, and that all submitted detections were produced by a model trained only on synthetic data I generated.

Training data used
------------------
The detector is trained exclusively on 19400 synthetic LiDAR frames produced by
my own scene generator. No real LiDAR label from any roadside-LiDAR dataset was
used for gradient updates, fine-tuning, or pseudo-label self-training.

Each synthetic frame composites
  (a) an analytic ground layer: points placed at the range where each of the real
      elevation channels intersects the ground, using the beam table shipped in
      the starting kit (meta.json), plus above-ground structure sampled from the
      static reference cloud (LUMPI_reference_cloud) provided with the kit;
  (b) object point clouds whose appearance is taken from unlabelled real point
      clusters (see Domain adaptation below), placed on HD-map lane polylines
      with per-class size, count and radial priors.
All object boxes in the synthetic frames are produced by my generator from my own
per-class size templates. No annotation of any real frame is copied into the
training set.

Domain adaptation and hyperparameter selection
----------------------------------------------
As permitted by the rules ("using the train split of the public real dataset for
hyperparameter selection or domain adaptation, provided no forbidden frame is
touched"), the following steps use real point clouds WITHOUT any label entering
the training set:
  1) Object appearance bank. From the point clouds of non-forbidden frames I
     extract object-shaped point clusters by unsupervised voxel connected
     components and reuse the resulting point patterns as object assets inside
     synthetic frames. No annotation and no ground-truth box of any real frame is
     read by the extraction; the boxes that label these points are generated by
     my own templates.
  2) Per-class size and count priors, score threshold, NMS IoU, top-k and epoch
     selection were chosen on non-forbidden real frames. Counts use the 1,513
     legal frames inside 006497-008109 after removing the 100 reserved ids; box
     sizes use all 8,020 legal frames.
  3) Submitted synthetic frames are post-processed with a monotone, per-point
     transform (centroid shift + radial CDF mapping + density-field resampling)
     fitted to the unlabelled point clouds of the same legal frames. This is the
     "calibrating the realism of your synthetic data (unlabelled clouds)" use
     explicitly allowed by the organizers.
  4) Inference-time box refinement only, driven by the point cloud. For every
     predicted box I generate a few candidate poses that vary only the degrees of
     freedom known to matter for that class (in-plane centre for Person and Truck,
     heading for Bicycle and Motorcycle, nothing for Car, Van and Bus, which the
     detector already places well) and keep the candidate that encloses the most
     LiDAR returns, requiring that the number of enclosed returns never decreases
     relative to the raw prediction. No real ground truth is involved, and the
     class-to-freedom assignment is the only real-data-tuned choice.
  5) Unlabelled re-ranking of the predicted boxes. Each box score is multiplied
     by a weight computed only from the point cloud inside the box,
     w = (n/(n+k))^b, where n is the number of LiDAR returns inside the box and
     (k, b) are per-class scalars. The scalars are the only real-data-tuned
     quantities here: they were selected by 2-fold cross-validation over
     non-forbidden real frames (one half selects, the other half confirms), and
     were retained only when both halves improved. No label is used at inference
     time and no model weight is fitted on real data.

Forbidden frames
----------------
The 100 ids in forbidden_frames.txt (50 of which are the scored test frames) were
never used for training, validation, hyperparameter selection, statistics or any
other stage. The 50 synthetic point clouds in this submission were produced by the
scene generator with seeds independent of the test frames.

Signature
---------
Team / individual name: liella722
Date (YYYY-MM-DD):      2026-11-11
Submission tag:         lumpi-simonly-pp-multiscale-geofit-unlabelled-rerank
"""


def main():
    z = zipfile.ZipFile(SRC)
    names = z.namelist()
    preds = z.read('predictions.json')
    synth = [(n, z.read(n)) for n in names if n.startswith('synthetic/')]
    z.close()
    with zipfile.ZipFile(DST, 'w', zipfile.ZIP_DEFLATED) as o:
        for n, b in synth:
            o.writestr(n, b)
        o.writestr('predictions.json', preds)
        o.writestr('declaration.txt', DECL)
    p = json.loads(preds)
    print('%s：%d 帧 %d 框 %.1f MB'
          % (DST, len(p), sum(len(v) for v in p.values()), os.path.getsize(DST) / 1e6))


if __name__ == '__main__':
    main()
